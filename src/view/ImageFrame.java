    private void btnPilihGambarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPilihGambarActionPerformed
        JFileChooser fc = new JFileChooser();
        fc.setDialogTitle("Pilih File Gambar");

        fc.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter(
            "File Gambar (*.jpg, *.jpeg, *.png, *.gif, *.bmp, *.jfif)",
            "jpg", "jpeg", "png", "gif", "bmp", "jfif"
        ));
        fc.setAcceptAllFileFilterUsed(false);

        int result = fc.showOpenDialog(this);

        if (result == JFileChooser.APPROVE_OPTION) {

            File sourceFile = fc.getSelectedFile();

            selectedFile = sourceFile;
            selectedPath = sourceFile.getAbsolutePath();
            imageChanged = true;

            txtPath.setText(sourceFile.getAbsolutePath());
            showPreview(sourceFile.getAbsolutePath());
        }
    }//GEN-LAST:event_btnPilihGambarActionPerformed

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        if (!validateForm()) return;

        if (selectedFile == null) {
            JOptionPane.showMessageDialog(this,
                "Silakan pilih gambar terlebih dahulu!",
                "Validasi",
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            selectedPath = copyToUploads(selectedFile);

            Category cat = (Category) cmbKategori.getSelectedItem();

            Image img = new Image();
            img.setCategoryId(cat.getId());
            img.setTitle(txtJudul.getText().trim());
            img.setDescription(txtDeskripsi.getText().trim());
            img.setImagePath(selectedPath);

            if (imageDAO.insert(img)) {
                JOptionPane.showMessageDialog(this,
                    "Gambar berhasil disimpan!",
                    "Sukses",
                    JOptionPane.INFORMATION_MESSAGE);

                resetForm();
                refreshAll();
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Gagal menyimpan gambar: " + e.getMessage(),
                "Error Database",
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        if (selectedId < 0) {
            JOptionPane.showMessageDialog(this,
                "Pilih data yang ingin diubah!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!validateForm()) return;

        try {
            Category cat = (Category) cmbKategori.getSelectedItem();

            Image img = new Image();
            img.setId(selectedId);
            img.setCategoryId(cat.getId());
            img.setTitle(txtJudul.getText().trim());
            img.setDescription(txtDeskripsi.getText().trim());

            Image oldImage = imageDAO.findById(selectedId);
            String finalPath = (oldImage != null) ? oldImage.getImagePath() : null;

            if (imageChanged && selectedFile != null) {
                if (oldImage != null) {
                    File oldFile = new File(oldImage.getImagePath());
                    if (oldFile.exists()) {
                        oldFile.delete();
                    }
                }
                finalPath = copyToUploads(selectedFile);
            }

            img.setImagePath(finalPath);

            if (imageDAO.update(img)) {
                JOptionPane.showMessageDialog(this,
                    "Gambar berhasil diubah!",
                    "Sukses",
                    JOptionPane.INFORMATION_MESSAGE);

                imageChanged = false;
                resetForm();
                refreshAll();
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Gagal mengubah gambar: " + e.getMessage(),
                "Error Database",
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        if (selectedId < 0) {
            JOptionPane.showMessageDialog(this,
                "Pilih data yang ingin dihapus!",
                "Peringatan",
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
            "Yakin ingin menghapus gambar ini?",
            "Konfirmasi",
            JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) return;

        try {
            Image oldImage = imageDAO.findById(selectedId);

            if (oldImage != null) {
                File oldFile = new File(oldImage.getImagePath());

                if (oldFile.exists()) {
                    oldFile.delete();
                }
            }

            if (imageDAO.delete(selectedId)) {
                JOptionPane.showMessageDialog(this,
                    "Gambar berhasil dihapus!",
                    "Sukses",
                    JOptionPane.INFORMATION_MESSAGE);

                resetForm();
                refreshAll();
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Gagal menghapus data: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnHapusActionPerformed

