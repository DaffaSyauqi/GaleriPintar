    private void loadKategoriCombo() {
        cmbKategori.removeAllItems();
        try {
            List<Category> list = categoryDAO.findAll();
            for (Category c : list) cmbKategori.addItem(c);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Gagal memuat kategori: " + e.getMessage(),
                "Error Database", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void loadFilterCombo() {
        cmbFilter.removeAllItems();
        cmbFilter.addItem(new Category(0, "Semua Kategori"));
        try {
            List<Category> list = categoryDAO.findAll();
            for (Category c : list) cmbFilter.addItem(c);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Gagal memuat filter: " + e.getMessage(),
                "Error Database", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void loadTable(int categoryId) {
        try {

            String keyword = txtSearch.getText().trim();

            List<Image> list;

            if (keyword.isEmpty()) {
                list = (categoryId == 0)
                        ? imageDAO.findAll()
                        : imageDAO.findByCategoryId(categoryId);
            } else {
                list = imageDAO.search(keyword, categoryId);
            }

            DefaultTableModel model =
                    (DefaultTableModel) tblGambar.getModel();

            model.setRowCount(0);

            for (Image img : list) {
                model.addRow(new Object[]{
                    img.getTitle(),
                    img.getCategoryName(),
                    img.getDescription(),
                    img.getImagePath(),
                    img.getCreatedAt()
                });
            }
            
            lblTotalData.setText("Total Data : " + model.getRowCount());

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                "Gagal memuat data gambar: " + e.getMessage(),
                "Error Database",
                JOptionPane.ERROR_MESSAGE);

        }
    }

    private void tblGambarValueChanged(javax.swing.event.ListSelectionEvent evt) {
        if (evt.getValueIsAdjusting()) return;
        int row = tblGambar.getSelectedRow();
        if (row < 0) return;

        try {
            int filterCatId = getSelectedFilterCategoryId();

            List<Image> list = (filterCatId == 0)
                    ? imageDAO.findAll()
                    : imageDAO.findByCategoryId(filterCatId);

            if (row < list.size()) {
                Image img = list.get(row);

                selectedId = img.getId();
                selectedFile = null;
                selectedPath = img.getImagePath();
                imageChanged = false;

                txtJudul.setText(img.getTitle());
                txtDeskripsi.setText(img.getDescription());
                txtPath.setText(img.getImagePath());

                for (int i = 0; i < cmbKategori.getItemCount(); i++) {
                    Category c = (Category) cmbKategori.getItemAt(i);
                    if (c.getId() == img.getCategoryId()) {
                        cmbKategori.setSelectedIndex(i);
                        break;
                    }
                }

                btnSimpan.setEnabled(false);
                btnUbah.setEnabled(true);
                btnHapus.setEnabled(true);

                showPreview(img.getImagePath());
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Gagal membaca data: " + e.getMessage(),
                "Error Database",
                JOptionPane.ERROR_MESSAGE);
        }
    }

    private int getSelectedFilterCategoryId() {
        Category selected = (Category) cmbFilter.getSelectedItem();
        return (selected == null) ? 0 : selected.getId();
    }

    private String copyToUploads(File source) throws IOException {
        File uploadsDir = new File("uploads");
        if (!uploadsDir.exists()) uploadsDir.mkdirs();

        String fileName = System.currentTimeMillis() + "_" + source.getName();
        File dest = new File(uploadsDir, fileName);
        Files.copy(source.toPath(), dest.toPath(), StandardCopyOption.REPLACE_EXISTING);
        return dest.getPath();
    }

    private void showPreview(String path) {
        if (path == null || path.isEmpty()) {
            lblPreview.setIcon(null);
            return;
        }

        File file = new File(path);

        if (!file.exists()) {
            lblPreview.setIcon(null);
            return;
        }

        try {
            BufferedImage original = ImageIO.read(file);

            if (original == null) {
                lblPreview.setIcon(null);
                return;
            }

            java.awt.Image scaled = scaleImage(original, 300, 220);

            lblPreview.setIcon(new ImageIcon(scaled));

        } catch (IOException e) {
            lblPreview.setIcon(null);
        }
    }

    private java.awt.Image scaleImage(BufferedImage src, int maxW, int maxH) {
        int w = src.getWidth();
        int h = src.getHeight();
        double ratio = Math.min((double) maxW / w, (double) maxH / h);
        int newW = (int) (w * ratio);
        int newH = (int) (h * ratio);
        return src.getScaledInstance(newW, newH, java.awt.Image.SCALE_SMOOTH);
    }

    private boolean validateForm() {
        if (txtJudul.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Judul tidak boleh kosong!");
            return false;
        }

        if (cmbKategori.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Pilih kategori!");
            return false;
        }

        if (selectedId < 0) {
            if (selectedPath == null || selectedPath.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                    "Pilih gambar terlebih dahulu!");
                return false;
            }
        }

        return true;
    }

    private void refreshAll() {
        loadTable(getSelectedFilterCategoryId());
    }
